package frc.robot;

import com.ctre.phoenix6.Utils;
import com.ctre.phoenix6.hardware.CANcoder;
import com.ctre.phoenix6.hardware.TalonFX;
import com.ctre.phoenix6.swerve.SwerveDrivetrain;
import com.ctre.phoenix6.swerve.SwerveRequest;
import edu.wpi.first.wpilibj.Notifier;
import edu.wpi.first.wpilibj.RobotController;
import edu.wpi.first.wpilibj.smartdashboard.Field2d;
import edu.wpi.first.wpilibj.smartdashboard.SmartDashboard;
import edu.wpi.first.wpilibj2.command.Command;
import edu.wpi.first.wpilibj2.command.CommandScheduler;
import edu.wpi.first.wpilibj2.command.Subsystem;
import java.util.function.Supplier;

/**
 * Phoenix 6's swerve drivetrain as a command-based subsystem.
 *
 * <p>In simulation it runs Phoenix's own simple physics on a 4 ms Notifier, the way robot projects
 * generated by Tuner X do. Under scrimmage those sim-state writes are blocked by the scrimmage agent
 * (it prints how many it ignored) and scrimmage's physics supplies the sensor values instead, so the
 * same code runs unchanged with or without scrimmage.
 */
public class Drivetrain extends SwerveDrivetrain<TalonFX, TalonFX, CANcoder> implements Subsystem {
  private static final double SIM_PERIOD = 0.004;  // seconds

  private final Field2d field = new Field2d();
  private Notifier simNotifier;
  private double lastSimTime;

  public Drivetrain() {
    super(TalonFX::new, TalonFX::new, CANcoder::new, Constants.DRIVETRAIN,
        Constants.FRONT_LEFT, Constants.FRONT_RIGHT, Constants.BACK_LEFT, Constants.BACK_RIGHT);
    CommandScheduler.getInstance().registerSubsystem(this);
    resetPose(Constants.START_POSE);
    SmartDashboard.putData("Field", field);
    if (Utils.isSimulation()) {
      startSimThread();
    }
  }

  /** A command that applies the request from {@code request} every loop while it runs. */
  public Command applyRequest(Supplier<SwerveRequest> request) {
    return run(() -> setControl(request.get()));
  }

  @Override
  public void periodic() {
    field.setRobotPose(getState().Pose);
  }

  private void startSimThread() {
    lastSimTime = Utils.getCurrentTimeSeconds();
    simNotifier = new Notifier(() -> {
      double now = Utils.getCurrentTimeSeconds();
      double dt = now - lastSimTime;
      lastSimTime = now;
      updateSimState(dt, RobotController.getBatteryVoltage());
    });
    simNotifier.setName("Drivetrain sim");
    simNotifier.startPeriodic(SIM_PERIOD);
  }
}
